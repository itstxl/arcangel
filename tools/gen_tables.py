#!/usr/bin/env python3
"""Extract ggml's quantisation lookup tables into src/quant_tables.h.

usage: gen_tables.py PATH/TO/ggml/src/ggml-common.h

The tables are copied verbatim (values and sizes) from llama.cpp's ggml-common.h (MIT licence), so the
engine decodes exactly what llama.cpp decodes. Re-run when moving to a newer llama.cpp.
"""
import re
import sys
from pathlib import Path

WANTED = ["kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid",
          "kvalues_iq4nl", "kvalues_fp4", "iq1s_grid"]
SIZES = {"NGRID_IQ1S": 2048}

src = Path(sys.argv[1]).read_text()
out = Path(__file__).resolve().parent.parent / "src" / "quant_tables.h"

lines = ["// Generated by tools/gen_tables.py from llama.cpp ggml/src/ggml-common.h (MIT licence). Do not edit.",
         "#pragma once", "", "#include <cstdint>", "", "namespace ink::tables {", ""]
for name in WANTED:
    m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*" + name + r",\s*(\w+)\)(.*?)GGML_TABLE_END\(\)", src, re.S)
    if not m:
        sys.exit(f"table {name} not found")
    ctype, size, body = m.group(1), m.group(2), m.group(3)
    size = SIZES.get(size, size)
    body = re.sub(r"//[^\n]*", "", body)
    values = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
    if len(values) != int(size):
        sys.exit(f"table {name}: {len(values)} values, expected {size}")
    lines.append(f"inline constexpr {ctype} {name}[{size}] = {{")
    for k in range(0, len(values), 8):
        lines.append("    " + ", ".join(values[k:k + 8]) + ",")
    lines.append("};")
    lines.append("")
lines.append("}  // namespace ink::tables")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({len(WANTED)} tables)")
